-- ── 022: AI credits ledger + xray_spec ────────────────────────────────────────
-- The metering layer behind the "smart tools" allowance (#13) and, new here, X-Ray for
-- orders that have no design. Rationale + pricing model: docs (spattoo-core)
-- AI_CREDITS_PLAN.md; tier values: SUBSCRIPTION_TIERS.md.
--
-- Apply manually to dev/prod Supabase (no migration runner). Safe to re-run.
--
-- ── THE TWO POOLS, AND WHY ONE OF THEM IS NOT A TABLE ───────────────────────────────
-- A baker spends from two different things, and they have different lifetimes:
--
--   1. The MONTHLY ALLOWANCE (subscription_plans.features.ai_credits_per_month). Resets
--      every calendar month. It is a COST CEILING, not a balance the baker owns.
--   2. The PURCHASED WALLET (top-up packs). Real money, does not reset.
--
-- The allowance is NOT stored as monthly "grant" rows. It is DERIVED: allowance_used =
-- the sum of this calendar month's debits, and remaining = plan value − that. Which means:
--   * no monthly grant job to run, fail, or run twice;
--   * no expiry sweep for the unused part;
--   * a plan change takes effect immediately and correctly, with no back-fill;
--   * the number is recomputable from the ledger alone, so it cannot drift out of sync.
-- This is deliberately the same shape as the X-Ray meter ("the first 5 orders confirmed in
-- the calendar month, recomputable from the order rows alone"). A mutable
-- `credits_remaining` integer would have neither property and would race under concurrency.
--
-- CALENDAR month, not billing period: an annual subscriber's period is 12 months long, so
-- metering per period would hand them 12x the allowance. Month boundaries are IST — the
-- bakers are in India and "this month" must mean what it means to them.
--
-- ── WHY THE ALLOWANCE IS PASSED IN, NOT LOOKED UP HERE ──────────────────────────────
-- reserve_ai_credits() takes p_allowance as an argument. It does NOT read
-- subscription_plans.features itself, because resolving a baker's entitlements involves the
-- subscription status gate (BLOCKED_STATUSES collapses everything to its fallback) and that
-- logic lives in ONE place: src/services/entitlements.js. Re-implementing it in SQL would
-- create a second source of truth that silently disagrees with the middleware and the client
-- the first time either changes. The caller resolves, the function enforces.

-- ── 1. credit_costs — what each action costs, as DATA ────────────────────────────────
-- Admin-authored master data, never a code constant. Model prices change, our retail price
-- should not have to ship a deploy to follow them (and mostly should NOT follow them — a
-- provider price drop is margin, not a price cut). One row per metered action.
--
-- COMPACT SURROGATE `id`, readable `action_key` UNIQUE beside it — the same shape as
-- order_statuses (supabase/order_status_surrogate.sql), and for the same reason. This is a
-- bounded lookup; credit_transactions is not, and it references this table on every row it
-- will ever have. Storing 'photo_to_xray_estimate' (22 bytes) there instead of a smallint
-- (2 bytes) would carry that on every row AND every index entry, forever. Do NOT reason from
-- today's row count — see CLAUDE.md "PERSISTED SCHEMA IS FOREVER". The surrogate never leaves
-- the server: services/aiCredits.js takes and returns action_key strings.
create table if not exists credit_costs (
  id         smallint    generated by default as identity primary key,
  action_key text        not null unique,                   -- 'photo_to_xray_estimate'
  credits    integer     not null check (credits > 0),      -- always whole credits, rounded UP
  label      text        not null,                          -- shown in the admin editor
  is_active  boolean     not null default true,             -- retire an action without deleting its history
  updated_at timestamptz not null default now()
);

-- Seed values are ILLUSTRATIVE and priced off landed cost at ~80% target gross margin
-- (AI_CREDITS_PLAN.md §2.3). 1 credit ~= Rs.1 of RETAIL value. Replace with figures from a
-- real provider invoice before charging anyone. Idempotent: re-running updates in place.
--
-- `label` is a SHORT JOB NOUN, and that is a UI contract, not a description. It must also be
-- UNIQUE among ACTIVE rows: the billing card lists them as "{label} — {credits} credits", so two
-- actions sharing a label render as the same job at two different prices and read as a bug. That
-- happened: photo_to_xray_estimate and element_build_guide were both "Build guide". Migration 026
-- now ENFORCES uniqueness with a partial unique index, so the rule no longer depends on anyone
-- reading this paragraph.
--
-- SUPERSEDED BY 030: labels are no longer required to be single countable nouns. That rule existed
-- because the card rendered "14 build guides left this month" by appending an "s"; that per-tool
-- countdown was removed (it implied separate budgets when every action draws on one pool) and the
-- label now renders verbatim. Both actions are X-Ray and now say so.
--
-- ONLY the built action is active. is_active means "currently offered", and an inactive row both
-- keeps the billing card honest (it would otherwise advertise three features that do not exist)
-- and makes reserve_ai_credits fail closed with UNKNOWN_ACTION if anything calls one early. Flip
-- each to true in the change that ships it.
insert into credit_costs (action_key, credits, label, is_active) values
  ('photo_to_xray_estimate', 15, 'X-Ray — read a cake photo',  true),
  ('photo_to_cake_design',   20, 'Cake design',  false),   -- not built
